export const generateQuiz = async ({ topic, conceptName, level }) => {
  console.log('Generating quiz with multi-model approach...');
  
  const prompt = `Create a 5-question multiple choice quiz on "${conceptName}" for a ${level} learner studying ${topic}.
Return ONLY valid JSON:
{
  "questions": [
    {
      "question": "Question text?",
      "options": ["A) ...", "B) ...", "C) ...", "D) ..."],
      "correctAnswer": "A",
      "explanation": "Why this is correct"
    }
  ]
}`;

  const responses = await fetchFromMultipleModels(prompt);
  
  // Try to parse JSON from responses
  for (const response of responses) {
    try {
      const jsonMatch = response.content.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        return JSON.parse(jsonMatch[0]);
      }
    } catch (e) {
      console.log(`Failed to parse quiz JSON from ${response.model}`);
    }
  }
  
  // Fallback to demo quiz
  return generateDemoQuiz(conceptName, topic);
};

// Demo data generators
function generateDemoRoadmap(topic, totalWeeks, level) {
  const weeks = [];
  const totalWeeksNum = parseInt(totalWeeks);
  
  // Generate roadmap for all requested weeks
  for (let i = 1; i <= totalWeeksNum; i++) {
    // Determine week category based on progress
    let weekCategory;
    if (i <= Math.floor(totalWeeksNum * 0.25)) {
      weekCategory = 'Fundamentals';
    } else if (i <= Math.floor(totalWeeksNum * 0.5)) {
      weekCategory = 'Core Concepts';
    } else if (i <= Math.floor(totalWeeksNum * 0.75)) {
      weekCategory = 'Intermediate Topics';
    } else {
      weekCategory = 'Advanced & Projects';
    }
    
    weeks.push({
      week: i,
      title: `Week ${i}: ${weekCategory}`,
      topics: [
        {
          id: `topic_${i}_1`,
          name: `${topic} - Topic ${i}.1`,
          estimatedHours: 3 + (i % 5), // Vary hours between 3-7
          difficulty: level,
          description: `Learn essential ${topic} concepts for week ${i}`
        },
        {
          id: `topic_${i}_2`,
          name: `${topic} - Topic ${i}.2`,
          estimatedHours: 4 + (i % 4), // Vary hours between 4-7
          difficulty: level,
          description: `Practice and apply week ${i} ${topic} concepts`
        },
        {
          id: `topic_${i}_3`,
          name: `${topic} - Topic ${i}.3`,
          estimatedHours: 2 + (i % 3), // Vary hours between 2-4
          difficulty: level,
          description: `Review and reinforce week ${i} learning`
        }
      ]
    });
  }
  
  return {
    title: `Complete ${topic} Mastery Course`,
    description: `Master ${topic} comprehensively in ${totalWeeks} weeks - From basics to advanced projects`,
    totalWeeks: totalWeeksNum,
    modules: weeks
  };
}

